import { createTurnTimingTracker } from '../../src/runtime/turn-timing.mjs';
import { assertEqual } from '../../tests/helpers/assert.mjs';
let now = 100;
const tracker = createTurnTimingTracker({ now: () => now });
tracker.start('old');
now = 200;
tracker.start('new');
assertEqual(tracker.mark('old', 'prepared'), false, 'late old attempt cannot commit timing');
assertEqual(tracker.mark('new', 'first-visible-token'), false, 'internal preprocessing cannot count as primary output');
now = 500;
tracker.mark('new', 'prepared', { operationId: 'operation' });
now = 800;
tracker.mark('new', 'completed');
assertEqual(tracker.snapshot().firstVisibleTokenMs, null, 'completion is never substituted for first token');
assertEqual(tracker.snapshot().unavailableReason, 'no-visible-stream-event', 'non-streaming limitation explicit');
assertEqual(tracker.snapshot().preprocessMs, 300, 'preprocessing duration measured');
tracker.start('invalidated');
tracker.mark('invalidated', 'prepared');
tracker.mark('invalidated', 'invalidate');
assertEqual(tracker.mark('invalidated', 'first-visible-token'), false, 'source invalidation closes token timing');
console.log('Turn timing tests passed.');
