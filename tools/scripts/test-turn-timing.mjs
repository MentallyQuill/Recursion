import { createTurnTimingTracker } from '../../src/runtime/turn-timing.mjs';
import { assertEqual } from '../../tests/helpers/assert.mjs';
let now = 100;
const tracker = createTurnTimingTracker({ now: () => now });
tracker.start('old');
now = 200;
tracker.start('new');
assertEqual(tracker.mark('old', 'prepared'), false, 'late old attempt cannot commit timing');
assertEqual(tracker.mark('old', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'normal' }), false, 'late old attempt cannot commit request readiness');
assertEqual(tracker.mark('new', 'first-visible-token'), false, 'internal preprocessing cannot count as primary output');
now = 500;
tracker.mark('new', 'prepared', { operationId: 'operation' });
now = 800;
tracker.mark('new', 'completed');
assertEqual(tracker.snapshot().firstVisibleTokenMs, null, 'completion is never substituted for first token');
assertEqual(tracker.snapshot().unavailableReason, 'no-visible-stream-event', 'non-streaming limitation explicit');
assertEqual(tracker.snapshot().preprocessMs, 300, 'preprocessing duration measured');
tracker.start('invalidated');
tracker.mark('invalidated', 'prepared');
tracker.mark('invalidated', 'invalidate');
assertEqual(tracker.mark('invalidated', 'first-visible-token'), false, 'source invalidation closes token timing');
assertEqual(tracker.mark('invalidated', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'normal' }), false, 'source invalidation closes request timing');
console.log('Turn timing tests passed.');

tracker.start('boundaries');
assertEqual(tracker.mark('boundaries', 'host-request-ready'), false, 'internal pre-preparation event is ignored');
now = 900;
tracker.mark('boundaries', 'prepared');
assertEqual(tracker.mark('boundaries', 'host-request-ready'), false, 'untyped settings events are ignored');
assertEqual(tracker.mark('boundaries', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'quiet' }), false, 'raw quiet requests are ignored without relying on generation-start events');
now = 1100;
assertEqual(tracker.mark('boundaries', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'normal' }), true, 'request-ready boundary recorded');
assertEqual(tracker.mark('boundaries', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'normal' }), false, 'duplicate request-ready cannot replace first boundary');
now = 1500;
tracker.mark('boundaries', 'first-visible-token');
now = 1800;
tracker.mark('boundaries', 'completed');
assertEqual(tracker.snapshot().preparedToRequestReadyMs, 200, 'host preparation after Recursion is measured separately');
assertEqual(tracker.snapshot().requestReadyToFirstVisibleTokenMs, 400, 'request-ready to first visible event measured separately');
assertEqual(tracker.snapshot().postPreparationMs, 600, 'post-preparation wait measured directly');
assertEqual(tracker.snapshot().visibleStreamingMs, 300, 'visible streaming excludes first-token wait');
tracker.start('no-boundaries');
tracker.mark('no-boundaries', 'prepared');
tracker.mark('no-boundaries', 'first-visible-token');
assertEqual(tracker.mark('no-boundaries', 'host-request-ready', { source: 'chat-completion-settings-ready', generationType: 'normal' }), false, 'late request-ready event cannot be attributed after output starts');
assertEqual(tracker.snapshot().requestReadyToFirstVisibleTokenMs, null, 'missing host milestone is never fabricated');
